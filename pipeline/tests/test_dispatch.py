# --- CONSTRAINTS -------------------------------------------------------------
def test_no_banned_word_in_either_rendering(plain, html):
    for name, message in (("text", plain), ("html", html)):
        found = BANNED_RE.findall(message)
        assert found == [], f"{name} rendering holds banned copy: {found}"


def test_the_banned_word_check_can_fail():
    """The guard above is only worth having if it fires. If this ever passes
    an empty list the check above is asserting nothing."""
    assert BANNED_RE.findall("this token is likely safe, you should buy")


def test_every_figure_carries_its_denominator(plain):
    """CONSTRAINTS.md #3. Every line that prints a percentage prints either
    the counts it was computed from or the n it was suppressed for."""
    for line in plain.splitlines():
        if "%" not in line:
            continue
        assert " of " in line or "n=" in line, f"percentage without its n: {line}"


def test_no_address_appears_in_the_message(plain, html):
    """CONSTRAINTS.md #2: no wallet or token address is ever a subject."""
    for message in (plain, html):
        assert re.search(r"0x[0-9a-fA-F]{40}", message) is None


def test_the_html_rendering_says_the_same_sentences_as_the_plain_one(composed, plain, html):
    for block in composed["blocks"]:
        for line in block["lines"]:
            assert line in plain
            assert dispatch.escape_html(line) in html


def test_the_html_is_the_design_idiom_and_holds_no_image(html):
    assert "#EFEAE0" in html  # --ground, the bone sheet
    assert "#16130F" in html  # --ink
    assert "border-radius" not in html
