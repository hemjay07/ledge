# --- the fixture itself ------------------------------------------------------
def test_the_fixture_number_file_is_what_recompute_derives():
    """The frozen number.json must be the pipeline's own output for the
    frozen partitions, or the fixture holds a figure the pipeline would
    never produce."""
    from pipeline.canonical import canonical_dumps
    from pipeline.recompute import recompute

    committed = (FIXTURE_DIR / "number.json").read_text()
    assert committed == canonical_dumps(recompute(FIXTURE_DIR))


def test_the_fixture_number_file_parses_as_schema_v2():
    number = json.loads((FIXTURE_DIR / "number.json").read_text())
    assert number["schemaVersion"] == 2
    assert set(number) >= {"h24", "allTime", "crawledAt", "firstIndexedAt"}
    assert "d7" not in number, "d7 stays internal to dispatch.py; see its docstring"
