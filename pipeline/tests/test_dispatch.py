"""
pipeline/dispatch.py — the weekly dispatch (ARCHITECTURE-PHASE2-4.md §11, day 9).

Binding rules exercised here:

  - Class A only. Every figure in the message is a count or a rate that came
    out of `pipeline/stats.py` over a window `stats.window` selected. The
    dispatch composes and formats; it never derives a statistic
    (ARCHITECTURE-PHASE2-4.md §0).
  - Never a number without its denominator (CONSTRAINTS.md #3): every line
    that prints a percentage prints the counts it came from.
  - Never fake precision (CONSTRAINTS.md #4): below n = 30 a figure renders
    "not enough data (n=…)", and the insight line — which is a fact, not a
    filler — is omitted rather than invented.
  - No sentence tells the reader what to do with a number (CONSTRAINTS.md
    NOT-THIS list), enforced here by the banned-word check over the whole
    rendered message, both renderings.

The fixture is frozen (`pipeline/tests/fixtures/dispatch/`, generated by
`make_dispatch_fixture.py`), so an hourly crawl can never move a test.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from pipeline import dispatch

FIXTURE_DIR = Path(__file__).resolve().parent / "fixtures" / "dispatch"


# --- the banned-word check --------------------------------------------------
# The list is the brief's, and it is applied with word boundaries for the
# word-shaped terms for the same reason scripts/lint-copy.sh does: a bare
# substring test for "edge" matches "ledge.tools", which the footer is
# required to carry, and a bare "ape" matches "shape". `probab` and `predict`
# are prefix-matched so "probability"/"probabilities"/"predicted" are caught.
# `will ` stays a literal: it is the future tense the copy must never take.
BANNED_PATTERNS = [
    r"\bscore\b", r"\bscores\b", r"\bscoring\b",
    r"\brisk\b", r"\brisks\b", r"\brisky\b",
    r"\bodds\b",
    r"\bchance\b", r"\bchances\b",
    r"\blikely\b",
    r"\bsafe\b", r"\bsafer\b", r"\bsafety\b",
    r"\brug\b", r"\brugs\b",
    r"\bprobab",
    r"\bpredict",
    r"will ",
    r"\bshould\b",
    r"\bbuy\b", r"\bbuys\b", r"\bbuying\b",
    r"\bsell\b", r"\bsells\b", r"\bselling\b",
    r"\bape\b", r"\bapes\b", r"\baping\b",
    r"\balpha\b",
    r"\bedge\b",
    r"\bsignals\b",
]
BANNED_RE = re.compile("|".join(BANNED_PATTERNS), re.IGNORECASE)


@pytest.fixture(scope="module")
def composed():
    return dispatch.compose(*dispatch.load_inputs(FIXTURE_DIR))


@pytest.fixture(scope="module")
def plain(composed):
    return dispatch.render_text(composed)


@pytest.fixture(scope="module")
def html(composed):
    return dispatch.render_html(composed)


