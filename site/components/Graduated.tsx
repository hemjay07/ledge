"use client";

/* /graduated: what a graduation actually looks like, and what just
   graduated. The distribution is the product -- the shape and the ladder
   lead, unchanged in substance from the first build -- and the rows beneath
   them are the evidence, defaulting to most-recently-graduated because a
   visitor here wants to know what just happened, with fastest-first kept one
   click away (REVAMP.md 2026-09-12, "the amendment", boards rebuild).

   Reuses /live's own vocabulary -- `.card`, `.card-header`, `.board-controls`,
   `.board-filter-disclosure`, `.board-what-counts`, `.state-tag`, `.live-card`
   -- rather than inventing a second visual language for a page that is
   structurally the same kind of board: one row per token, sortable and
   filterable by columns every row already shows (CONSTRAINTS 1), no score,
   no grade, no verdict. The column count and the card's own lead figure
   differ from /live's, so the table/card responsive toggle gets its own
   class names (`.graduated-table-wrap` / `.graduated-cards`) rather than
   inheriting /live's fixed eight-column widths.

   The build-time row list (public/graduated.json, generated by
   scripts/generate-graduated.mjs) holds 2,500+ rows and rising, so only the
   FIRST PAGE -- the first 50 rows, in whichever order the page's own default
   sort wants -- ships in the HTML, passed in as `initialRows`. Any other
   sort, filter or page fetches the same public/graduated.json the rest of
   the site already serves, once, then holds it in state.

   Every duration is a Class B fact: one token's own graduation minus its own
   launch. This component sorts and filters the rows it is given -- it never
   computes a share, a rate, or a percentage of its own; the ladder above it
   is the population figure, read verbatim from data/number.json and gated at
   n = 30, and this component never recomputes it. */

